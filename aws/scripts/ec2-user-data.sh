#!/usr/bin/env bash
# ==============================================================================
# CloudOps Sentinel - EC2 Cloud-Init User Data Bootstrap Script
# Operating System: Amazon Linux 2023 / Ubuntu 22.04 LTS
# Role: Automated Provisioning, IAM Secrets Fetching & Service Bootstrapping
# ==============================================================================

set -euo pipefail

# ------------------------------------------------------------------------------
# 1. Variables & Path Setup
# ------------------------------------------------------------------------------
APP_DIR="/opt/cloudops-sentinel"
CONFIG_DIR="/etc/cloudops-sentinel"
LOG_DIR="/var/log/cloudops-sentinel"
AWS_REGION=$(curl -s http://169.254.169.254/latest/meta-data/placement/region || echo "us-east-1")
SECRET_ID="cloudops-sentinel/production/secrets"

echo "[$(date -u +%FT%TZ)] [INFO] Starting CloudOps Sentinel EC2 Bootstrap in region ${AWS_REGION}..."

# ------------------------------------------------------------------------------
# 2. Base Packages & Dependencies Installation
# ------------------------------------------------------------------------------
if command -v dnf &>/dev/null; then
    # Amazon Linux 2023
    dnf update -y
    dnf install -y docker git jq curl postgresql16 aws-cli amazon-cloudwatch-agent
    systemctl enable --now docker
elif command -v apt-get &>/dev/null; then
    # Ubuntu 22.04 LTS
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -y
    apt-get install -y docker.io docker-compose-v2 git jq curl postgresql-client awscli
    # Install CloudWatch Agent
    curl -s https://s3.${AWS_REGION}.amazonaws.com/amazoncloudwatch-agent-${AWS_REGION}/ubuntu/amd64/latest/amazon-cloudwatch-agent.deb -o /tmp/amazon-cloudwatch-agent.deb
    dpkg -i -E /tmp/amazon-cloudwatch-agent.deb
    systemctl enable --now docker
fi

# Ensure docker compose plugin exists
if ! docker compose version &>/dev/null; then
    mkdir -p /usr/local/lib/docker/cli-plugins
    curl -SL https://github.com/docker/compose/releases/download/v2.24.5/docker-compose-linux-x86_64 -o /usr/local/lib/docker/cli-plugins/docker-compose
    chmod +x /usr/local/lib/docker/cli-plugins/docker-compose
fi

# ------------------------------------------------------------------------------
# 3. Directories & Secure Permissions
# ------------------------------------------------------------------------------
mkdir -p "${APP_DIR}" "${CONFIG_DIR}" "${LOG_DIR}"
chmod 755 "${LOG_DIR}"
chmod 700 "${CONFIG_DIR}"

# ------------------------------------------------------------------------------
# 4. Fetch Secrets from AWS Secrets Manager via IAM Instance Profile
# ------------------------------------------------------------------------------
echo "[$(date -u +%FT%TZ)] [INFO] Retrieving application secrets from AWS Secrets Manager (${SECRET_ID})..."

SECRET_JSON=$(aws secretsmanager get-secret-value \
    --region "${AWS_REGION}" \
    --secret-id "${SECRET_ID}" \
    --query SecretString \
    --output text 2>/dev/null || echo "{}")

if [ "${SECRET_JSON}" != "{}" ]; then
    echo "[$(date -u +%FT%TZ)] [INFO] Successfully retrieved secrets. Formatting /etc/cloudops-sentinel/.env.production..."
    echo "# Production environment variables generated by cloud-init" > "${CONFIG_DIR}/.env.production"
    
    echo "${SECRET_JSON}" | jq -r 'to_entries | .[] | "\(.key)=\(.value)"' >> "${CONFIG_DIR}/.env.production"
    chmod 600 "${CONFIG_DIR}/.env.production"
else
    echo "[$(date -u +%FT%TZ)] [WARN] Secret ${SECRET_ID} not found or empty. Using template placeholder."
fi

# ------------------------------------------------------------------------------
# 5. Configure & Start AWS CloudWatch Agent
# ------------------------------------------------------------------------------
echo "[$(date -u +%FT%TZ)] [INFO] Configuring CloudWatch Agent..."
if [ -f "${APP_DIR}/aws/config/amazon-cloudwatch-agent.json" ]; then
    /opt/aws/amazon-cloudwatch-agent/bin/amazon-cloudwatch-agent-ctl \
        -a fetch-config \
        -m ec2 \
        -s \
        -c file:"${APP_DIR}/aws/config/amazon-cloudwatch-agent.json"
fi

# ------------------------------------------------------------------------------
# 6. Setup Automated Daily S3 Backup Cron
# ------------------------------------------------------------------------------
cat << 'CRONEVAL' > /etc/cron.d/cloudops-s3-backup
0 2 * * * root /opt/cloudops-sentinel/aws/scripts/aws_backup_to_s3.sh >> /var/log/cloudops-sentinel/backup.log 2>&1
CRONEVAL
chmod 644 /etc/cron.d/cloudops-s3-backup

echo "[$(date -u +%FT%TZ)] [INFO] EC2 Bootstrap complete. Sentinel instance ready for deployment."

